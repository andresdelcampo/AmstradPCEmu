"""Generate THIRD-PARTY-NOTICES.md from the runtime DLLs shipped in local/dist.

Maps each DLL to its MSYS2 (mingw64) package and reads license, version and
upstream URL from pacman. Re-run after changing the toolchain or the DLL set.
"""
from pathlib import Path
import subprocess, collections, sys

root = Path(__file__).resolve().parents[1]
dist = root / 'local/dist'
msys = Path(r'C:\msys64')
pacman = str(msys / 'usr/bin/pacman.exe')
bindir = msys / 'mingw64/bin'

def run(*a):
    return subprocess.run([pacman, *a], capture_output=True, text=True).stdout

pkgs = collections.OrderedDict()
for dll in sorted(dist.rglob('*.dll')):
    src = bindir / dll.name
    if not src.exists():  # Qt plugins live under share/qt5/plugins
        found = list((msys / 'mingw64').rglob(dll.name))
        src = found[0] if found else None
    owner = run('-Qo', '/' + src.relative_to(msys).as_posix()) if src else ''
    if ' is owned by ' not in owner:
        print('unowned:', dll.relative_to(dist), file=sys.stderr); continue
    name = owner.strip().split(' is owned by ')[1].split()[0]
    pkgs.setdefault(name, []).append(dll.relative_to(dist).as_posix())

def field(info, key):
    for line in info.splitlines():
        if line.startswith(key):
            return line.split(':', 1)[1].strip()
    return ''

out = ['# Third-party notices', '',
 'AmstradPCEmu is a patched build of 86Box (GPL-2.0-or-later) that also contains a CRT',
 'shader ported from IBMulator (GPL-3.0-or-later). The combined program is distributed',
 'under GPL-3.0-or-later; see `LICENSE`, `COPYING-86Box`, `COPYING-IBMulator` and',
 '`assets/shaders/NOTICE-IBMulator.md`.', '',
 'The runtime libraries below ship next to the executable as separate DLLs. Their',
 'source and license texts are available from the package/upstream links. Where a',
 'library is LGPL, the DLL can be replaced with a compatible build.', '',
 '| Package (MSYS2 mingw64) | Version | License | Upstream | Files |',
 '|---|---|---|---|---|']
for name, files in pkgs.items():
    info = run('-Qi', name)
    out.append('| {} | {} | {} | {} | {} |'.format(
        name, field(info, 'Version'), field(info, 'Licenses') or field(info, 'License'),
        field(info, 'URL'), ', '.join(f'`{f}`' for f in files)))
out += ['', 'Other bundled components:', '',
 '- **86Box** (https://github.com/86Box/86Box): GPL-2.0-or-later, with embedded third-party',
 '  code under its own headers (softfloat, libchdr/zstd/LZMA/miniz, LGPL-3.0-or-later `lzw`).',
 '- **IBMulator** (https://github.com/barotto/IBMulator): GPL-3.0-or-later, CRT shader.',
 '- **Floppy-drive sounds**: recorded by the project author and contributed to 86Box.',
 '- **Front-panel artwork**: created by the project author with AI image tools; no third-party',
 '  artwork is reproduced.',
 '', 'This file is generated by `scripts/gen-third-party-notices.py`.']
(root / 'THIRD-PARTY-NOTICES.md').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
print('wrote THIRD-PARTY-NOTICES.md with', len(pkgs), 'packages')
